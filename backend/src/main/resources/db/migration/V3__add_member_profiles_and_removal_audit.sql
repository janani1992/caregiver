CREATE TABLE membership_removal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circle_id UUID NOT NULL REFERENCES circle(id) ON DELETE CASCADE,
    user_id UUID NOT NULL,
    removed_by UUID NOT NULL,
    removed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_membership_active_roster ON membership (circle_id, removed_at, joined_at);
CREATE INDEX ix_membership_removal_history ON membership_removal (circle_id, user_id, removed_at DESC);
