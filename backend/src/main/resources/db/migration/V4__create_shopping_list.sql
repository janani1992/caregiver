CREATE TABLE list_item (
    id UUID PRIMARY KEY,
    circle_id UUID NOT NULL REFERENCES circle(id) ON DELETE CASCADE,
    item_text VARCHAR(200) NOT NULL,
    original_language VARCHAR(12) NOT NULL DEFAULT 'en',
    qty INTEGER,
    unit VARCHAR(32),
    shop_group VARCHAR(64),
    status VARCHAR(16) NOT NULL DEFAULT 'NEEDED' CHECK (status IN ('NEEDED', 'CLAIMED', 'BOUGHT', 'NOT_FOUND')),
    claimed_by UUID,
    version BIGINT NOT NULL DEFAULT 1,
    request_hash CHAR(64) NOT NULL,
    created_by UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    removed_at TIMESTAMP WITH TIME ZONE,
    removed_by UUID,
    CONSTRAINT ck_list_item_qty CHECK (qty IS NULL OR qty > 0),
    CONSTRAINT ck_list_item_text CHECK (length(trim(item_text)) > 0)
);

CREATE INDEX ix_list_item_circle_status ON list_item (circle_id, status, created_at DESC);
CREATE INDEX ix_list_item_circle_shop ON list_item (circle_id, shop_group);

CREATE TABLE list_item_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circle_id UUID NOT NULL REFERENCES circle(id) ON DELETE CASCADE,
    item_id UUID NOT NULL REFERENCES list_item(id) ON DELETE CASCADE,
    actor UUID NOT NULL,
    event_type VARCHAR(16) NOT NULL CHECK (event_type IN ('CREATED', 'CLAIMED', 'BOUGHT', 'REMOVED')),
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    payload TEXT NOT NULL DEFAULT '{}',
    at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_list_item_event_actor_key UNIQUE (actor, idempotency_key)
);

CREATE INDEX ix_list_item_event_item ON list_item_event (circle_id, item_id, at);
