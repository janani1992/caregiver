CREATE TABLE urgent_request (
    id UUID PRIMARY KEY,
    circle_id UUID NOT NULL REFERENCES circle(id) ON DELETE CASCADE,
    item_id UUID REFERENCES list_item(id) ON DELETE SET NULL,
    text VARCHAR(500) NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (state IN ('OPEN', 'ON_IT', 'RESOLVED')),
    sender UUID NOT NULL,
    handled_by UUID,
    handled_at TIMESTAMP WITH TIME ZONE,
    resolved_by UUID,
    resolved_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 1,
    request_hash CHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_urgent_request_text CHECK (length(trim(text)) > 0),
    CONSTRAINT ck_urgent_request_state_fields CHECK (
        (state = 'OPEN' AND handled_by IS NULL AND resolved_by IS NULL) OR
        (state = 'ON_IT' AND handled_by IS NOT NULL AND resolved_by IS NULL) OR
        (state = 'RESOLVED' AND resolved_by IS NOT NULL)
    )
);

CREATE INDEX ix_urgent_request_circle_state ON urgent_request (circle_id, state, created_at DESC);
CREATE INDEX ix_urgent_request_item ON urgent_request (circle_id, item_id);

CREATE TABLE urgent_request_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circle_id UUID NOT NULL REFERENCES circle(id) ON DELETE CASCADE,
    request_id UUID NOT NULL REFERENCES urgent_request(id) ON DELETE CASCADE,
    actor UUID NOT NULL,
    event_type VARCHAR(16) NOT NULL CHECK (event_type IN ('CREATED', 'SEEN', 'ON_IT', 'RESOLVED')),
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_urgent_event_actor_key UNIQUE (actor, idempotency_key)
);

CREATE INDEX ix_urgent_event_request ON urgent_request_event (circle_id, request_id, at);
CREATE INDEX ix_urgent_event_actor ON urgent_request_event (request_id, actor, event_type);
